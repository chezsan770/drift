// The Rust core is built by cargo-ndk and its Kotlin bindings generated by
// uniffi-bindgen, once per build variant. AGP wires both outputs in as
// generated sources, so `assembleDebug` builds everything in order.

val coreDir: File = rootProject.file("../core")
val cargoTargetDir = local("rust.targetDir").ifEmpty { coreDir.resolve("target").path }
val sdkDir = local("sdk.dir").ifEmpty { System.getenv("ANDROID_HOME") ?: "" }
val cargoBin = File(System.getProperty("user.home"), ".cargo/bin/cargo" + if (System.getProperty("os.name").startsWith("Windows")) ".exe" else "")
    .takeIf { it.exists() }?.path ?: "cargo"

abstract class CargoNdkTask : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val sources: DirectoryProperty
    @get:InputFile @get:PathSensitive(PathSensitivity.RELATIVE) abstract val manifest: RegularFileProperty
    @get:Input abstract val profile: Property<String>
    @get:Input abstract val abis: ListProperty<String>
    @get:Internal abstract val workDir: DirectoryProperty
    @get:Internal abstract val cargo: Property<String>
    @get:Internal abstract val targetDir: Property<String>
    @get:Internal abstract val ndkHome: Property<String>
    @get:OutputDirectory abstract val outDir: DirectoryProperty
    @get:Inject abstract val execOps: ExecOperations

    @TaskAction
    fun build() {
        outDir.get().asFile.deleteRecursively()
        execOps.exec {
            workingDir = this@CargoNdkTask.workDir.get().asFile
            environment("CARGO_TARGET_DIR", targetDir.get())
            environment("ANDROID_NDK_HOME", ndkHome.get())
            commandLine(
                listOf(cargo.get(), "ndk") +
                    abis.get().flatMap { listOf("-t", it) } +
                    listOf("--platform", "26", "-o", outDir.get().asFile.path,
                        "build", "-p", "drift-core", "--lib", "--profile", profile.get())
            )
        }
    }
}

abstract class UniffiBindgenTask : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val libs: DirectoryProperty
    @get:Internal abstract val workDir: DirectoryProperty
    @get:Internal abstract val cargo: Property<String>
    @get:Internal abstract val targetDir: Property<String>
    @get:OutputDirectory abstract val outDir: DirectoryProperty
    @get:Inject abstract val execOps: ExecOperations

    @TaskAction
    fun generate() {
        outDir.get().asFile.deleteRecursively()
        outDir.get().asFile.mkdirs()
        execOps.exec {
            workingDir = this@UniffiBindgenTask.workDir.get().asFile
            environment("CARGO_TARGET_DIR", targetDir.get())
            commandLine(
                cargo.get(), "run", "-q", "-p", "drift-core", "--features", "bindgen",
                "--bin", "uniffi-bindgen", "--",
                "generate",
                "--library", libs.get().file("arm64-v8a/libdrift_core.so").asFile.path,
                "--language", "kotlin", "--no-format",
                "--out-dir", outDir.get().asFile.path,
            )
        }
        check(outDir.get().asFileTree.matching { include("**/*.kt") }.files.isNotEmpty()) {
            "uniffi-bindgen produced no Kotlin. Is the Rust library stripped?"
        }
    }
}

androidComponents {
    onVariants { variant ->
        val cap = variant.name.replaceFirstChar { it.uppercase() }
        val cargoTask = tasks.register<CargoNdkTask>("cargoBuild$cap") {
            description = "Builds libdrift_core.so with cargo-ndk"
            sources.set(coreDir.resolve("drift-core/src"))
            manifest.set(coreDir.resolve("drift-core/Cargo.toml"))
            profile.set(if (variant.buildType == "release") "release" else "android-dev")
            abis.set(listOf("arm64-v8a", "x86_64"))
            workDir.set(coreDir)
            cargo.set(cargoBin)
            targetDir.set(cargoTargetDir)
            ndkHome.set("$sdkDir/ndk/$ndkVer")
        }
        val bindgenTask = tasks.register<UniffiBindgenTask>("uniffiBindgen$cap") {
            description = "Generates Kotlin bindings from the Rust library"
            libs.set(cargoTask.flatMap { it.outDir })
            workDir.set(coreDir)
            cargo.set(cargoBin)
            targetDir.set(cargoTargetDir)
        }
        variant.sources.jniLibs?.addGeneratedSourceDirectory(cargoTask, CargoNdkTask::outDir)
        variant.sources.kotlin?.addGeneratedSourceDirectory(bindgenTask, UniffiBindgenTask::outDir)
    }
}
